"""Write cases/drawbar_frame_h*.mech: the drawbar linkage loaded by the frame weight at its centre
of gravity (12 085 kg = machine mass 12 400 kg less the 315 kg drawbar). The height h of the centre
of gravity above the frame beam AB is not known and is varied; for each h the position along the beam
is set so that the hitch reaction equals the 7650 kg of the operating manual at ED = 935 mm (the
reaction is linear in that position, so two evaluations suffice).
Usage (repository root): python3 examples/usarya/make_drawbar_frame.py [build/cylload]
"""
import math, os, subprocess, sys

B = sys.argv[1] if len(sys.argv) > 1 else 'build/cylload'
U = os.path.dirname(os.path.abspath(__file__))
KIN = open(os.path.join(U, 'drawbar_load.mech')).read().split('# V g at the hitch')[0].split('title')[1].split('\n', 1)[1]
BX, BY = 4900.41877, 881.09979
L = math.hypot(BX, BY)
UX, UY, NX, NY = BX / L, BY / L, -BY / L, BX / L
M = 12400.0 - 315.0


def text(h, x, y):
    return (f"""# CleanField / Usarya SCS-100 stone picker - drawbar lifting, empty hopper, physical load model.
# Kinematics as drawbar.mech; two cylinders 100/50 in parallel are modelled as one with twice the piston
# area. The frame carries its own weight at its centre of gravity: machine mass 12 400 kg less the drawbar
# (315 kg, on the drawbar) = 12 085 kg. The centre of gravity lies {h} mm above the frame beam AB (normal
# to it); its position along the beam is set so that the hitch reaction is the 7650 kg of the operating
# manual at ED = 935 mm. The axle (A) and hitch (level) reactions then follow from the kinematics.
# Generated by make_drawbar_frame.py. Units mm, kg.
title Usarya stone picker - drawbar lifting, frame weight at its centre of gravity ({h} mm above the beam)
""" + KIN.strip() + f"\nmass frame_carried frame {x:.4f} {y:.4f} {M:.0f} 0\n")


def hitch(h, s):
    x, y = s * UX + h * NX, s * UY + h * NY
    path = os.path.join(U, 'cases', 'drawbar_frame_tmp.mech')
    open(path, 'w').write(text(h, x, y))
    out = subprocess.run([B, 'pose', path, 'ED=935'], capture_output=True, text=True, check=True).stdout
    os.remove(path)
    return float([l for l in out.splitlines() if l.startswith('level')][0].split()[2]) / 9.81


for h in (0, 500, 1000, 1500, 2000):
    r0, r1 = hitch(h, 0.0), hitch(h, 1000.0)
    s = (7650.0 - r0) / (r1 - r0) * 1000.0
    x, y = s * UX + h * NX, s * UY + h * NY
    open(os.path.join(U, 'cases', f'drawbar_frame_h{h:04d}.mech'), 'w').write(text(h, x, y))
    print(f'h = {h:4d} mm: centre of gravity {s:.1f} mm along AB, ({x:.1f}, {y:.1f}) mm')
